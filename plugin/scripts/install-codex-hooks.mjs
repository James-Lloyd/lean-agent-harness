#!/usr/bin/env node

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const pluginRoot = path.dirname(scriptDir);
const marker = "Lean Agent Harness user hooks for Codex (managed by harness-codex-activate).";
const generatorMarker = "GENERATED by lean-agent-harness codex-setup (";
const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const targetIndex = args.indexOf("--target");
if (targetIndex >= 0 && !args[targetIndex + 1]) throw new Error("--target requires a path");
const target = path.resolve(targetIndex >= 0 ? args[targetIndex + 1] : path.join(os.homedir(), ".codex", "hooks.json"));

const source = JSON.parse(fs.readFileSync(path.join(pluginRoot, "hooks", "hooks.json"), "utf8"));
source.description = marker;
for (const groups of Object.values(source.hooks ?? {})) {
  for (const group of groups) {
    for (const hook of group.hooks ?? []) {
      if (hook.type === "command") hook.command = hook.command.replaceAll("${PLUGIN_ROOT}", pluginRoot.replaceAll("\\", "/"));
    }
  }
}
const rendered = `${JSON.stringify(source, null, 2)}\n`;

if (checkOnly) {
  if (!fs.existsSync(target)) {
    console.error(`NOT installed: ${target}`);
    process.exit(1);
  }
  const current = fs.readFileSync(target, "utf8");
  if (current !== rendered) {
    console.error(`STALE or not harness-owned: ${target}`);
    process.exit(1);
  }
  console.log(`fresh: ${target}`);
  process.exit(0);
}

if (fs.existsSync(target)) {
  let current;
  try { current = JSON.parse(fs.readFileSync(target, "utf8")); } catch { current = {}; }
  const owned = current.description === marker
    || (typeof current.description === "string" && current.description.startsWith(generatorMarker))
    || (typeof current._generated_by === "string" && current._generated_by.startsWith(generatorMarker));
  if (!owned) {
    throw new Error(`refusing to overwrite non-harness hooks: ${target}; merge plugin/hooks/hooks.json manually`);
  }
}

fs.mkdirSync(path.dirname(target), { recursive: true });
const temporary = `${target}.lean-agent-harness.tmp`;
fs.writeFileSync(temporary, rendered, { encoding: "utf8", mode: 0o600 });
fs.renameSync(temporary, target);
console.log(`installed ${marker}: ${target}`);
console.log("Open /hooks in a new Codex session and review/trust the four entries before relying on them.");
