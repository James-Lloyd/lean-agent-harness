#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const pluginRoot = path.dirname(scriptDir);
const commandsDir = path.join(pluginRoot, "commands");
const skillsDir = path.join(pluginRoot, "skills");
const checkOnly = process.argv.includes("--check");
const marker = "<!-- generated by plugin/scripts/sync-command-skills.mjs; edit plugin/commands instead -->";

function skillName(commandName) {
  return commandName.startsWith("harness-") ? commandName : `harness-${commandName}`;
}

function parseDescription(source, commandName) {
  const match = source.match(/^description:\s*(.+)$/m);
  if (!match) throw new Error(`plugin/commands/${commandName}.md has no description`);
  return match[1].trim();
}

function render(commandName, description) {
  const name = skillName(commandName);
  const yamlDescription = JSON.stringify(
    `${description} Use when the user invokes $${name}, asks for ${name.replace("harness-", "harness ")}, or requests this workflow.`,
  );
  return `---\nname: ${name}\ndescription: ${yamlDescription}\n---\n\n${marker}\n\n# ${name}\n\nRead [the shared Codex adapter](../../references/codex-command-adapter.md), then follow the canonical\n[/${commandName} command](../../commands/${commandName}.md) with the user's request as \`$ARGUMENTS\`.\n`;
}

const expected = new Map();
for (const file of fs.readdirSync(commandsDir).filter((name) => name.endsWith(".md")).sort()) {
  const commandName = path.basename(file, ".md");
  const source = fs.readFileSync(path.join(commandsDir, file), "utf8");
  expected.set(skillName(commandName), render(commandName, parseDescription(source, commandName)));
}

const failures = [];
for (const [name, content] of expected) {
  const dir = path.join(skillsDir, name);
  const target = path.join(dir, "SKILL.md");
  if (checkOnly) {
    if (!fs.existsSync(target)) failures.push(`missing ${path.relative(pluginRoot, target)}`);
    else if (fs.readFileSync(target, "utf8") !== content) failures.push(`stale ${path.relative(pluginRoot, target)}`);
  } else {
    fs.mkdirSync(dir, { recursive: true });
    if (fs.existsSync(target)) {
      const current = fs.readFileSync(target, "utf8");
      if (!current.includes(marker) && current !== content) {
        throw new Error(`refusing to overwrite hand-written skill: ${path.relative(pluginRoot, target)}`);
      }
    }
    fs.writeFileSync(target, content);
  }
}

for (const entry of fs.readdirSync(skillsDir, { withFileTypes: true })) {
  if (!entry.isDirectory() || expected.has(entry.name)) continue;
  const target = path.join(skillsDir, entry.name, "SKILL.md");
  if (fs.existsSync(target) && fs.readFileSync(target, "utf8").includes(marker)) {
    failures.push(`orphaned generated skill ${path.relative(pluginRoot, target)}`);
  }
}

if (failures.length) {
  console.error(failures.join("\n"));
  process.exitCode = 1;
} else if (checkOnly) {
  console.log(`command skills are synchronized (${expected.size})`);
} else {
  console.log(`synchronized ${expected.size} command skills`);
}
